// Pure request parsing, response handling and predicate evaluation, shared by
// the sandbox harness and by Redfall's own test suite.
//
// Splitting these out means the code that decides whether an exploit worked can
// be verified without a container. It contains no I/O against the target.
//
// The same split covers multi-step chain PoCs: substitution between steps,
// value extraction and the step loop itself all live here, so a chain verdict
// can be reproduced against a live server on a host with no gVisor.

import { createHmac } from 'node:crypto';

export function parseRawRequest(raw) {
  const text = String(raw).replace(/\r\n/g, '\n');
  const splitAt = text.indexOf('\n\n');
  const head = splitAt === -1 ? text : text.slice(0, splitAt);
  let body = splitAt === -1 ? '' : text.slice(splitAt + 2);
  const lines = head.split('\n');
  const [method, path] = lines[0].split(' ');
  const headers = {};
  for (const line of lines.slice(1)) {
    const idx = line.indexOf(':');
    if (idx === -1) continue;
    headers[line.slice(0, idx).trim().toLowerCase()] = line.slice(idx + 1).trim();
  }
  return { method: method || 'GET', path: path || '/', headers, body };
}

/**
 * Decode a `Transfer-Encoding: chunked` body. Node's http server chunks any
 * response whose length it does not know up front, which is most of them, so
 * skipping this leaves the chunk-size prefixes inside the body and every JSON
 * parse fails.
 */
export function dechunk(bodyBuf) {
  const out = [];
  let offset = 0;
  for (;;) {
    const lineEnd = bodyBuf.indexOf('\r\n', offset);
    if (lineEnd === -1) break;
    const sizeHex = bodyBuf.toString('ascii', offset, lineEnd).split(';')[0].trim();
    const size = Number.parseInt(sizeHex, 16);
    if (!Number.isFinite(size) || Number.isNaN(size)) break;
    if (size === 0) break;
    const start = lineEnd + 2;
    out.push(bodyBuf.subarray(start, start + size));
    offset = start + size + 2;
    if (offset > bodyBuf.length) break;
  }
  return Buffer.concat(out);
}

export function parseHttpResponse(headText, bodyBuf) {
  const statusLine = String(headText).split('\r\n')[0] || '';
  const status = Number((statusLine.match(/HTTP\/1\.[01] (\d{3})/) || [])[1] || 0);
  const headers = {};
  for (const line of String(headText).split('\r\n').slice(1)) {
    const idx = line.indexOf(':');
    if (idx === -1) continue;
    headers[line.slice(0, idx).trim().toLowerCase()] = line.slice(idx + 1).trim();
  }
  let raw = Buffer.isBuffer(bodyBuf) ? bodyBuf : Buffer.from(String(bodyBuf ?? ''), 'binary');
  const chunked = String(headers['transfer-encoding'] || '').toLowerCase().includes('chunked');
  if (chunked) raw = dechunk(raw);
  const body = raw.toString('utf8');
  let json = null;
  try {
    json = JSON.parse(body);
  } catch {
    json = null;
  }
  return { status, body, text: body, json, headers };
}

export function csvFields(body) {
  const out = [];
  for (const line of String(body).split(/\r?\n/)) {
    if (!line.trim()) continue;
    let field = '';
    let quoted = false;
    for (let i = 0; i < line.length; i += 1) {
      const ch = line[i];
      if (ch === '"') {
        quoted = !quoted;
      } else if (ch === ',' && !quoted) {
        out.push(field);
        field = '';
      } else {
        field += ch;
      }
    }
    out.push(field);
  }
  return out;
}

// Binding names the PoC predicate contract exposes. `static` is a reserved word
// under strict mode, so the generated function body deliberately omits the
// "use strict" directive — otherwise every single predicate would throw.
//
// `steps`, `values` and `step` are the multi-step bindings: a chain PoC runs
// several requests in order and a predicate can inspect every earlier step and
// every value an earlier step extracted.
export const BINDING_NAMES = [
  'status',
  'body',
  'text',
  'json',
  'headers',
  'csvFields',
  'psql',
  'probe',
  'followup',
  'followup_status',
  'setup_status',
  'steps',
  'values',
  'step',
  'static',
  'extra',
];

export function evaluate(expr, ctx) {
  const values = BINDING_NAMES.map((name) => (name in ctx ? ctx[name] : undefined));
  // The predicate is generated by Redfall and only ever runs inside the sandbox.
  // eslint-disable-next-line no-new-func
  const fn = new Function(...BINDING_NAMES, `return (${expr});`);
  return fn(...values);
}

export function bindings(res, extra = {}, psql = () => '') {
  return {
    status: res ? res.status : 0,
    body: res ? res.body : '',
    text: res ? res.body : '',
    json: res ? res.json : null,
    headers: res ? res.headers : {},
    csvFields: () => csvFields(res ? res.body : ''),
    psql,
    probe: extra.probe || {},
    followup: extra.followup || null,
    followup_status: extra.followup_status ?? null,
    setup_status: extra.setup_status ?? null,
    steps: extra.steps || [],
    values: extra.values || {},
    step: extra.step ?? null,
    static: extra.static || {},
    extra: extra.extra || {},
  };
}

export function median(values) {
  const sorted = [...values].sort((a, b) => a - b);
  return sorted.length ? sorted[Math.floor(sorted.length / 2)] : 0;
}

// ------------------------------------------------------- multi-step chains
//
// A chain PoC is a list of steps, each one a real request. A value produced by
// an earlier response is written into a later request through `{{NAME}}`, so the
// data flow between the steps is what makes the chain a chain. Nothing here
// decides that a step is vulnerable: each step's own predicate does, exactly as
// it would standing alone, and the chain is only credited with the joins whose
// two steps both held.

const PLACEHOLDER = /\{\{([A-Z0-9_]+)\}\}/g;

/** Replace `{{NAME}}` with a value an earlier step produced. */
export function substitute(raw, values) {
  return String(raw).replace(PLACEHOLDER, (whole, name) => {
    if (Object.prototype.hasOwnProperty.call(values, name)) return values[name];
    throw new Error(`step references {{${name}}} but no earlier step produced it`);
  });
}

/**
 * Turn a raw chain-step request into the fields the socket write needs.
 *
 * The body has already been rewritten by substitution, so the Content-Length
 * the fragment was generated with describes a body that no longer exists; it is
 * dropped and recomputed here. A Transfer-Encoding declaration is left alone,
 * because a chunked body is framed by the caller.
 */
export function prepareStepRequest(rawRequest) {
  const req = splitRawRequest(rawRequest);
  const headers = {};
  for (const [key, value] of Object.entries(req.headers)) {
    if (key === 'content-length' || key === 'host' || key === 'connection') continue;
    headers[key] = value;
  }
  if (req.body && !Object.keys(headers).some((key) => key.toLowerCase() === 'transfer-encoding')) {
    headers['Content-Length'] = String(Buffer.byteLength(req.body));
  }
  return { method: req.method, path: req.path, headers, body: req.body };
}

/** The placeholder names a request depends on, in order of appearance. */
export function placeholders(raw) {
  const out = [];
  for (const match of String(raw).matchAll(PLACEHOLDER)) out.push(match[1]);
  return out;
}

/**
 * Split a raw request into method, path, headers and body without rewriting it.
 *
 * `parseRawRequest` normalises every CRLF to LF, which is right for JSON and
 * wrong for multipart: RFC 7578 requires CRLF between parts, so a rewritten body
 * no longer matches the Content-Length that describes it and the server waits
 * for bytes that never arrive. Chain steps are stitched from raw fragments, so
 * they are split here instead, and a multipart body is normalised to CRLF on
 * purpose rather than by accident.
 */
export function splitRawRequest(raw) {
  const text = String(raw);
  const crlfAt = text.indexOf('\r\n\r\n');
  const splitAt = crlfAt !== -1 ? crlfAt : text.indexOf('\n\n');
  const sepLen = crlfAt !== -1 ? 4 : 2;
  const head = splitAt === -1 ? text : text.slice(0, splitAt);
  let body = splitAt === -1 ? '' : text.slice(splitAt + sepLen);
  if (/multipart\/form-data/i.test(head)) {
    // Only rebuild line endings when the body actually needs it. A body that is
    // already CRLF throughout was built with a correct Content-Length, and
    // rewriting it would invalidate that length.
    const alreadyCrlf = !/(^|[^\r])\n/.test(body);
    if (!alreadyCrlf) {
      body = body.replace(/\r?\n/g, '\r\n');
      if (!body.endsWith('\r\n')) body += '\r\n';
    }
  }

  const lines = head.split(/\r?\n/).filter((line) => line.trim() !== '');
  const [method, path] = (lines[0] || 'GET /').split(' ');
  const headers = {};
  for (const line of lines.slice(1)) {
    const idx = line.indexOf(':');
    if (idx === -1) continue;
    headers[line.slice(0, idx).trim().toLowerCase()] = line.slice(idx + 1).trim();
  }
  return { method: method || 'GET', path: path || '/', headers, body };
}

/** Split a dotted path into key / index / wildcard segments. */
export function tokenizePath(path) {
  const out = [];
  for (const chunk of String(path).split('.')) {
    if (!chunk) continue;
    const head = chunk.match(/^([^[\]]*)/)[1];
    if (head) out.push({ key: head });
    for (const index of chunk.matchAll(/\[(\*|\d+)\]/g)) {
      out.push(index[1] === '*' ? { star: true } : { index: Number(index[1]) });
    }
  }
  return out;
}

/** Every value the path reaches. `a.b` yields at most one; `a[*].b` yields many. */
export function pathMatches(root, path) {
  let current = [root];
  for (const segment of tokenizePath(path)) {
    const next = [];
    for (const value of current) {
      if (value === null || value === undefined) continue;
      if (segment.key !== undefined) {
        if (typeof value === 'object' && segment.key in value) next.push(value[segment.key]);
      } else if (segment.star) {
        if (Array.isArray(value)) next.push(...value);
        else if (typeof value === 'object') next.push(...Object.values(value));
      } else if (Array.isArray(value)) {
        if (segment.index < value.length) next.push(value[segment.index]);
      } else if (typeof value === 'object' && String(segment.index) in value) {
        next.push(value[segment.index]);
      }
    }
    current = next;
  }
  return current;
}

function toText(value) {
  if (typeof value === 'string') return value;
  if (value === null || value === undefined) return '';
  if (typeof value === 'object') return JSON.stringify(value);
  return String(value);
}

/** Choose one value out of a possibly-wildcarded path. */
export function pickValue(matches, selector) {
  const pick = selector.pick || 'first';
  const texts = matches.map(toText);
  if (pick === 'first') return texts[0];
  if (pick === 'last') return texts[texts.length - 1];
  if (pick === 'longest') {
    return texts.slice().sort((a, b) => b.length - a.length)[0];
  }
  if (pick === 'first_starts_with') {
    const prefix = String(selector.starts_with ?? '');
    if (!prefix) throw new Error('pick=first_starts_with needs `starts_with`');
    return texts.find((text) => text.startsWith(prefix));
  }
  if (pick === 'first_contains') {
    const needle = String(selector.contains ?? '');
    if (!needle) throw new Error('pick=first_contains needs `contains`');
    return texts.find((text) => text.includes(needle));
  }
  if (pick === 'first_matching') {
    const pattern = String(selector.pattern ?? '');
    if (!pattern) throw new Error('pick=first_matching needs `pattern`');
    const re = new RegExp(pattern);
    return texts.find((text) => re.test(text));
  }
  throw new Error(`unknown pick mode ${JSON.stringify(pick)}`);
}

/** Base64url-encode a buffer or string. */
function b64url(input) {
  return Buffer.from(input).toString('base64url');
}

/**
 * Sign an HS256 JWT off-box with a key the chain just stole, the way an
 * attacker would: the application is not asked to mint this token.
 */
export function jwtHs256(secret, claims, extraClaims = {}) {
  if (!secret) throw new Error('jwt_hs256 needs a secret');
  const header = b64url(JSON.stringify(extraClaims.alg ? { typ: 'JWT', ...extraClaims } : { alg: 'HS256', typ: 'JWT' }));
  const payload = b64url(
    JSON.stringify({ ...(claims || {}), iat: Math.floor(Date.now() / 1000) }),
  );
  const signature = createHmac('sha256', String(secret)).update(`${header}.${payload}`).digest();
  return `${header}.${payload}.${b64url(signature)}`;
}

/** Fill `{{NAME}}` inside every string in a selector object and check it is bound. */
export function fillSelector(selector, values) {
  if (typeof selector === 'string') return substitute(selector, values);
  if (Array.isArray(selector)) return selector.map((item) => fillSelector(item, values));
  if (selector && typeof selector === 'object') {
    const out = {};
    for (const [key, value] of Object.entries(selector)) out[key] = fillSelector(value, values);
    return out;
  }
  return selector;
}

/**
 * Evaluate one extraction selector against a real response.
 *
 * Selectors are declarative so a chain proposal can be checked structurally
 * before anything runs: an unknown `from` or a missing `path` is refused at
 * validation time, not discovered mid-chain.
 */
export function selectValue(selector, res) {
  const from = selector.from;
  if (from === 'status') return res.status;
  if (from === 'body') return res.body;
  if (from === 'header') {
    const name = String(selector.name || '').toLowerCase();
    if (!name) throw new Error('header selector needs `name`');
    return res.headers[name];
  }
  if (from === 'json') {
    if (!selector.path) throw new Error('json selector needs `path`');
    return pickValue(pathMatches(res.json, selector.path), selector);
  }
  if (from === 'json_text') {
    if (!selector.path) throw new Error('json_text selector needs `path`');
    const inner = pickValue(pathMatches(res.json, selector.path), selector);
    if (inner === undefined || inner === null) return inner;
    const parsed = JSON.parse(String(inner));
    return selector.field ? parsed[selector.field] : parsed;
  }
  if (from === 'base64' || from === 'base64url') {
    if (selector.value === undefined) throw new Error(`${from} selector needs \`value\``);
    const encoding = from === 'base64' ? 'base64' : 'base64url';
    return Buffer.from(String(selector.value), encoding).toString('utf8');
  }
  if (from === 'jwt_hs256') {
    return jwtHs256(selector.secret, selector.claims || {}, selector.header || {});
  }
  throw new Error(`unknown extraction source ${JSON.stringify(from)}`);
}

/** Run a step's `extract` map and fail loudly when it produces nothing. */
export function extractValues(spec, res, values = {}) {
  const out = {};
  for (const [name, selector] of Object.entries(spec || {})) {
    if (!/^[A-Z][A-Z0-9_]*$/.test(name)) {
      throw new Error(`extraction name ${JSON.stringify(name)} must be upper-case with underscores`);
    }
    // An extraction may be derived from one produced earlier in the same map —
    // `FORGED` is signed with the `SIGNING_KEY` the same response leaked — so
    // the scope grows as the map is walked, in insertion order.
    const filled = fillSelector(selector, { ...values, ...out });
    const value = selectValue(filled, res);
    const text = toText(value);
    if (!text) throw new Error(`extraction ${name} produced nothing (${JSON.stringify(selector)})`);
    out[name] = text;
  }
  return out;
}

/**
 * Run a multi-step chain against a `send` implementation.
 *
 * `send(rawRequest)` returns the parsed response. Optional `before` / `after`
 * hooks run a step's setup and follow-up requests around its own request, so a
 * step derived from a standalone PoC keeps that PoC's preconditions and
 * postconditions. The loop is deliberately pure apart from the calls it is
 * handed, so the verdict logic the sandbox relies on is the same code a host
 * test exercises.
 */
export async function runStepChain(steps, options) {
  const { send, psql = () => '', bindExtra = {}, extra = {}, hooks = {} } = options || {};
  const values = { ...(extra.values || {}) };
  const records = [];
  const evidence = [];
  let last = null;

  const failed = (kind, step, message, stepsPassed) => ({
    ok: false,
    stepsPassed,
    steps: records,
    values,
    evidence,
    failure: { kind, step, message },
    last,
  });

  for (let index = 0; index < steps.length; index += 1) {
    const step = steps[index];
    let raw;
    try {
      raw = substitute(step.request, values);
    } catch (err) {
      return failed('unbound', index, err.message, index);
    }

    let setup = null;
    if (hooks.before) {
      try {
        setup = await hooks.before(step, index, { values, substitute: (text) => substitute(text, values) });
      } catch (err) {
        return failed('setup-error', index, err.message, index);
      }
      if (setup && setup.evidence) evidence.push(setup.evidence);
      if (setup && setup.ok === false) return failed('setup', index, setup.message || 'setup predicate did not hold', index);
    }

    let res;
    try {
      res = await send(raw);
    } catch (err) {
      return failed('send', index, err.message, index);
    }
    last = res;

    let followup = null;
    if (hooks.after) {
      try {
        followup = await hooks.after(step, index, { values, res, substitute: (text) => substitute(text, values) });
      } catch (err) {
        return failed('followup-error', index, err.message, index);
      }
      if (followup && followup.evidence) evidence.push(followup.evidence);
      if (followup && followup.ok === false) {
        return failed('followup', index, followup.message || 'followup predicate did not hold', index);
      }
    }

    let ok = false;
    let error = '';
    try {
      const ctx = bindings(
        res,
        {
          probe: { ...(extra.probe || {}), step: index + 1 },
          steps: records,
          values,
          step: index + 1,
          followup: followup ? followup.res : null,
          followup_status: followup ? followup.res.status : null,
          setup_status: setup ? setup.res.status : null,
          ...bindExtra,
        },
        psql,
      );
      ok = evaluate(step.expect_expr, ctx) === true;
    } catch (err) {
      error = `${err.name}: ${err.message}`;
    }

    records.push({
      n: index + 1,
      id: step.id || step.finding_id || '',
      ok,
      status: res.status,
      body: res.body.slice(0, 600),
    });
    evidence.push(`step ${index + 1}${step.id ? ` ${step.id}` : ''} -> ${res.status} ${res.body.slice(0, 500)}`);

    if (!ok) {
      evidence.push(error ? `step ${index + 1} predicate error: ${error}` : `step ${index + 1} predicate did NOT hold`);
      return failed(error ? 'predicate-error' : 'predicate', index, error, index);
    }

    if (step.extract && Object.keys(step.extract).length) {
      try {
        Object.assign(values, extractValues(step.extract, res, values));
      } catch (err) {
        evidence.push(`step ${index + 1} extraction failed: ${err.message}`);
        return failed('extract', index, err.message, index + 1);
      }
    }
  }

  let ok = true;
  let error = '';
  if (extra.expectExpr) {
    try {
      const ctx = bindings(
        last,
        { probe: { ...(extra.probe || {}), step: records.length }, steps: records, values, step: records.length, ...bindExtra },
        psql,
      );
      ok = evaluate(extra.expectExpr, ctx) === true;
    } catch (err) {
      ok = false;
      error = `${err.name}: ${err.message}`;
    }
    if (!ok) {
      evidence.push(error ? `chain predicate error: ${error}` : 'chain predicate did NOT hold');
      return failed(error ? 'predicate-error' : 'predicate', records.length - 1, error, records.length);
    }
  }

  return { ok: true, stepsPassed: records.length, steps: records, values, evidence, failure: null, last };
}

/** The default final predicate of a generated chain PoC. */
export function chainExpectExpr(maxSteps) {
  return `steps.length === ${maxSteps} && steps.every((s) => s.ok === true)`;
}

// ------------------------------------------------------------------ targets
// Which runtime a target directory needs, decided from the files a caller
// actually listed from disk. No file, no runtime: an unknown tree is an error
// the harness reports, never a default it invents.
export function detectTargetKind(files) {
  if (files.includes('package.json')) return 'node';
  if (files.includes('requirements.txt') || files.includes('pyproject.toml') || files.includes('setup.py')) {
    return 'python';
  }
  return null;
}

/**
 * The Python boot contract, resolved to argv + cwd + env.
 *
 *   1. `redfall.target.json` is explicit and authoritative: `start` is the argv
 *      handed to the interpreter, `cwd` (optional) is relative to the target
 *      root, `health` (optional) defaults to /health, `env` (optional) adds
 *      variables. `$PORT` inside any string is replaced by the effective port.
 *   2. Without a config, a bare `app.py` at the target root is the documented
 *      fallback.
 *   3. Anything else returns null; the harness turns that into a real
 *      `target-missing` failure rather than guessing an entrypoint.
 */
export function resolvePythonStart(config, options) {
  const { port, rootHasAppPy } = options;
  const fill = (value) => String(value).replace(/\$PORT/g, String(port));
  if (config && Array.isArray(config.start) && config.start.length > 0) {
    const env = {};
    for (const [key, value] of Object.entries(config.env || {})) env[key] = fill(value);
    return {
      args: config.start.map(fill),
      cwd: config.cwd ? fill(config.cwd) : '',
      health: config.health ? fill(config.health) : '/health',
      env,
    };
  }
  if (rootHasAppPy) return { args: ['-u', 'app.py'], cwd: '', health: '/health', env: {} };
  return null;
}
