class _LiteralDumper(yaml.SafeDumper):
    """Multiline strings (raw HTTP requests) as literal blocks, for readability."""


def _str_representer(dumper: yaml.SafeDumper, data: str):
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_LiteralDumper.add_representer(str, _str_representer)


def build_document() -> dict:
    vulns = []
    for entry in SPEC:
        rel_path, pattern, symbol = ANCHORS[entry["id"]]
        doc = {key: entry[key] for key in ("id", "route", "category", "cwe", "severity")}
        doc["location"] = {
            "file": rel_path,
            "symbol": symbol,
            "lines": [anchor_line(rel_path, pattern)],
        }
        doc["description"] = entry["description"]
        doc["poc"] = entry["poc"]
        doc["fix"] = {"strategy": FIX_STRATEGIES[entry["id"]]}
        doc["tests_that_must_stay_green"] = list(TESTS)
        vulns.append(doc)
    return {"version": 1, "target": "pythonbank", "note": NOTE, "vulns": vulns}


def dump(document: dict) -> str:
    return yaml.dump(
        document,
        Dumper=_LiteralDumper,
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
        width=110,
    )


def main() -> int:
    text = dump(build_document())
    check = "--check" in sys.argv[1:]
    if check:
        current = MANIFEST_PATH.read_text(encoding="utf-8") if MANIFEST_PATH.exists() else ""
        if current != text:
            print("manifest.yaml is stale: run python scripts/write_manifest.py", file=sys.stderr)
            return 1
        print(f"manifest.yaml is current ({len(SPEC)} vulns): {MANIFEST_PATH}")
        return 0
    MANIFEST_PATH.write_text(text, encoding="utf-8")
    print(f"wrote {MANIFEST_PATH} ({len(SPEC)} vulns)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
