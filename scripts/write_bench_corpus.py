#!/usr/bin/env python3
"""Generate a bench corpus from a range target's manifest.

The recall scorer needs a sealed list of flows that exist. The range targets
already carry exactly that — a manifest of real vulnerabilities with real
file, symbol and line anchors, verified by the range runner. Generating the
corpus from the manifest rather than hand-writing it means the corpus and the
ground truth cannot drift: there is one source for "these flows exist".

The generated corpus separates three files the arena treats differently:

  manifest.json       what was committed before any run
  budget.json         the ceiling every tool gets, including the baselines
  ground-truth.json   the answers — read only by the scorer

The seed is recorded so a corpus is pinned to the commit that produced it.

Usage:
    python scripts/write_bench_corpus.py              # all range targets
    python scripts/write_bench_corpus.py pythonbank   # one
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
BENCH = ROOT / "bench" / "corpora"

# Language by target. The corpus records it so per-language recall is
# reportable; a flow in a Python target that the Java engine misses is not a
# Python failure and the scorer must be able to tell.
TARGET_LANGUAGE = {
    "pythonbank": "python",
    "vulnbank": "typescript",
    "vulnbank-adaptive": "typescript",
    "chainbank": "typescript",
}

# One ceiling for every tool on every corpus. Identical by construction, which
# is the point: a comparison where one side spent ten times as much is not a
# comparison of tools.
BUDGET = {
    "wall_clock_s": 1800,
    "tokens": 500_000,
    "sandbox_minutes": 60.0,
    "usd": 10.0,
}


def _category_alias(category: str) -> str:
    """The category key the engine's taint stage emits, so the two agree.

    The manifest uses the range runner's vocabulary; the engine emits sink
    kinds it maps through `range_runner.match.CATEGORY_ALIASES`. Keeping the
    corpus in the manifest's own vocabulary and letting the scorer compare
    canonical forms is what stops a rename in one place from silently making
    recall zero.
    """
    return (category or "").strip()


def build(target: str) -> dict:
    manifest_path = ROOT / "range" / target / "manifest.yaml"
    if not manifest_path.is_file():
        raise SystemExit(f"no manifest for {target}: {manifest_path}")
    document = yaml.safe_load(manifest_path.read_text(encoding="utf-8"))
    # Two manifest shapes exist: `vulns` (pythonbank, vulnbank and the
    # adaptive one) and `findings` (chainbank, whose unit is the chain step).
    # Both name real anchors, so both can seed a corpus.
    vulns = document.get("vulns") or document.get("findings") or []
    if not vulns:
        raise SystemExit(f"{target}: manifest declares neither vulns nor findings")

    language = TARGET_LANGUAGE.get(target, "unknown")
    expected = []
    truth = []
    for vuln in vulns:
        location = vuln.get("location") or {}
        lines = location.get("lines") or []
        line = int(lines[0]) if lines else 0
        if not location.get("file") or line <= 0:
            # A manifest entry without an anchor cannot be scored: the scorer
            # matches on file and line, so a flow with no location would be
            # unmissable and unfindable at once. Refuse it loudly.
            raise SystemExit(
                f"{target}/{vuln.get('id')}: no file+line anchor; cannot be a corpus entry"
            )
        entry = {
            "id": vuln["id"],
            "language": language,
            "category": _category_alias(vuln["category"]),
            "file": location["file"],
            "symbol": location.get("symbol") or "",
            "line": line,
            "proof_contract": (vuln.get("poc") or {}).get("expect", ""),
        }
        expected.append(entry)
        truth.append(
            {
                **entry,
                "cwe": vuln.get("cwe", ""),
                "severity": vuln.get("severity", ""),
                "description": (vuln.get("description") or "").strip(),
                "route": vuln.get("route", ""),
            }
        )

    seed = hashlib.sha256(
        json.dumps(truth, sort_keys=True).encode("utf-8")
    ).hexdigest()[:16]

    return {
        "manifest.json": {
            "name": target,
            "version": "1",
            "seed": seed,
            "note": (
                "Generated by scripts/write_bench_corpus.py from "
                f"range/{target}/manifest.yaml. Committed before any run. "
                "The ground truth is read only by the scorer."
            ),
            "expected": expected,
        },
        "budget.json": dict(BUDGET),
        "ground-truth.json": {"findings": truth},
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("targets", nargs="*", default=None)
    args = parser.parse_args()

    targets = args.targets or sorted(TARGET_LANGUAGE)
    written = 0
    for target in targets:
        files = build(target)
        out = BENCH / target
        out.mkdir(parents=True, exist_ok=True)
        for name, document in files.items():
            (out / name).write_text(
                json.dumps(document, indent=2, sort_keys=False) + "\n", encoding="utf-8"
            )
        count = len(files["manifest.json"]["expected"])
        print(f"wrote bench/corpora/{target}: {count} expected flow(s)")
        written += 1

    if written == 0:
        print("nothing generated", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
